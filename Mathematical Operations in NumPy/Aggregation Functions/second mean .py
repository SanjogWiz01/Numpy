import numpy as np
arr = [[5, 17, 1, 33, 8], 
	[5, 6, 27, 8, 9], 
	[5, 2, 54, 89, 4,]] 
print("\nMEAN OF GIVEN 2 D ARRAY : ", np.mean(arr)) 
print("\nmean of arr, axis = 0 : ", np.mean(arr, axis = 0)) # UP TO DOWN MEAN
print("\nmean of arr, axis = 1 : ", np.mean(arr, axis = 1)) # SID E WIZE MEANNNN
