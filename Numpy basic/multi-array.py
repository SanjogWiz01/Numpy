import numpy as np
# Create a 2d array
sanjog =np.array([[1, 2, 3], [4, 5, 6]])
print(sanjog) #print 2d array
print(sanjog.ndim) #dimension
print(sanjog.shape) #print shape
print(sanjog.size)  #print size
print(sanjog.dtype) #print datatype
print(sanjog.itemsize) #print itemsize
print(sanjog.nbytes)    #print nbytes